"""Reproduce submission evidence. Run from src: .venv/Scripts/python scripts/check_day9.py."""
from pathlib import Path
import os
import subprocess
import sys

COMMANDS = [
    ('lab9.smoke', 0),
    ('lab9.evalset --check', 0),
    ('lab9.evalset --v2 --check', 0),
    ('pytest -q', 0),
    ('pytest -q -m student -o addopts= -k lab9', 0),
    ('pytest -q -o addopts=', 0),
    ('lab9.eval --shape swarm --out reports/baseline_v1.json', 0),
    ('lab9.eval --shape fixed --out reports/eval_fixed.json', 0),
    ('lab9.eval --shape seeded_regression --out reports/eval_seeded_regression.json', 0),
    ('lab9.eval --shape swarm --spec config/metric_spec_v2.yaml --out reports/baseline_v2.json', 0),
    ('lab9.eval --shape slice_regression --spec config/metric_spec_v2.yaml --out reports/eval_slice_regression.json', 0),
    ('lab9.eval --shape swarm --out reports/eval_pr.json', 0),
    ('lab9.ci_check --pr reports/eval_pr.json --baseline reports/baseline_v1.json', 0),
    ('lab9.gate --pr reports/eval_pr.json --baseline reports/baseline_v1.json', 0),
    ('lab9.gate --pr reports/eval_fixed.json --baseline reports/baseline_v1.json', 0),
    ('lab9.gate --pr reports/eval_seeded_regression.json --baseline reports/baseline_v1.json', 1),
    ('lab9.mutation --detect', 0),
    ('lab9.mutation --spec config/metric_spec_v2.yaml --baseline reports/baseline_v2.json', 0),
    ('lab9.mutation --spec config/metric_spec_v2.yaml --aa 66,77,88,99,110', 0),
    ('lab9.traps --pr reports/eval_slice_regression.json --baseline reports/baseline_v2.json --spec config/metric_spec_v2.yaml', 0),
    ('lab9.judge --csv data/eval/judge_tone_public.csv --audit 5', 0),
    ('lab9.judge --csv data/eval/judge_helpful_public.csv --audit 5', 1),
]
for name in ('evaluator_errors_as_nan', 'dropped_failing_rows', 'cherry_picked_seeds', 'loosened_spec'):
    spec = (f'reports/traps/{name}.spec.yaml --base-spec config/metric_spec_v2.yaml'
            if name == 'loosened_spec' else 'config/metric_spec_v2.yaml')
    COMMANDS.append((f'lab9.gate --pr reports/traps/{name}.json --baseline reports/baseline_v2.json --spec {spec}', 1))


def main():
    os.chdir(Path(__file__).resolve().parents[1])
    sys.stdout.reconfigure(encoding='utf-8')
    evidence = Path('../docs/day9_terminal_evidence.md')
    failed = []
    with evidence.open('w', encoding='utf-8') as out:
        out.write('# Day 9 terminal evidence\n\nGenerated by `src/scripts/check_day9.py`. Expected exit 1 means a regression or uncalibrated judge was correctly blocked.\n')
        for command, expected in COMMANDS:
            # Empty pytest addopts is an actual empty argument, not a shell quoting workaround.
            args = command.split()
            print(f'Running {command}', flush=True)
            proc = subprocess.run([sys.executable, '-m', *args], capture_output=True,
                                  text=True, encoding='utf-8', errors='replace',
                                  env={**os.environ, 'PYTHONUTF8':'1'})
            output = '\n'.join(line.rstrip() for line in (proc.stdout + proc.stderr).splitlines())
            out.write(f'\n## python -m {command}\n\n```text\n{output}\nexit={proc.returncode}; expected={expected}\n```\n')
            out.flush()
            print(f'exit {proc.returncode} (expected {expected})', flush=True)
            if proc.returncode != expected:
                failed.append(command)
    print(f'{len(COMMANDS)-len(failed)}/{len(COMMANDS)} checks passed; evidence: {evidence}')
    return bool(failed)


if __name__ == '__main__':
    raise SystemExit(main())
