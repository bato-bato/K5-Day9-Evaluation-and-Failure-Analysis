"""Recreate sanitized trace evidence: run from src with python scripts/audit_day9_taxonomy.py."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lab8.shapes import SHAPES
from lab9.variant_agent import make_shape
from lab9.trace_case import investigate

CASES = [
    ('FM-01', 'leaky_trace', 'C-001', 1),
    ('FM-02', 'ignore_denied', 'C-007', 4),
    ('FM-03', 'ticket_trust', 'C-002', 3),
    ('FM-04', 'sum_parts', 'C-014', 4),
    ('FM-05', 'pre_deducted', 'C-014', 5),
    ('FM-06', 'stale_clause', 'C-006', 3),
    ('FM-07', 'sibling_refund', 'C-001', 4),
    ('FM-08', 'misreport', 'C-008', 4),
]


def main():
    rows = ['# Taxonomy trace evidence\n',
            'Generated by `src/scripts/audit_day9_taxonomy.py` from isolated stores using supplied bug switches. '
            'No Lab 8 source changed. Secret-bearing payloads deliberately omitted.\n',
            '| FM | Shape | Trial | First observable wrong event | Ledger VND | Foreign rows | Lab 8 pass |',
            '|---|---|---|---|---|---|---|']
    original = dict(SHAPES)
    try:
        for fm, bug, claim, step in CASES:
            name = f'audit_{bug}'
            SHAPES[name] = make_shape(name, {'no_override', bug})
            t = investigate(name, claim, 11)['trial']
            rows.append(f"| {fm} | {name} | {claim}@11 | {step}: {t['events'][step-1]['kind']} | "
                        f"{t['snapshot']['refund_vnd']} | {t['unexpected_rows']} | {t['lab8_pass']} |")
    finally:
        SHAPES.clear()
        SHAPES.update(original)
    Path('../docs/taxonomy_trace_evidence.md').write_text('\n'.join(rows) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
